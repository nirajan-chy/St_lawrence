#include <stdio.h>

int main(void) {
    int x = 15;
    int y = 10;

    printf("x > y : %d\n", x > y);
    printf("x < y : %d\n", x < y);
    printf("x >= y : %d\n", x >= y);
    printf("x <= y : %d\n", x <= y);
    printf("x == y : %d\n", x == y);
    printf("x != y : %d\n", x != y);

    return 0;
}
